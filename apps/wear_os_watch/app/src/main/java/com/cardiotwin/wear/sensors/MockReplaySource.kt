package com.cardiotwin.wear.sensors

import android.content.Context
import com.cardiotwin.wear.data.Reading
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.isActive
import kotlinx.coroutines.launch
import org.json.JSONObject
import java.time.Instant
import java.time.temporal.ChronoUnit
import kotlin.math.max
import kotlin.random.Random

/**
 * MOCK MODE. Plays a saved SIMULATED watch stream (assets/mock/replay_stay_<id>.json) as if the sensors produced it.
 * The file was generated by the backend's own virtual watch (backend/simulator/watch_sim.py, seed 0) from a held-out
 * MIMIC-IV demo ICU test stay: hourly charted vitals interpolated every 5 minutes with small noise; HRV, steps, sleep
 * and QTc are synthetic. Times are re-stamped at start so every run is new data to the backend.
 *
 * Readings use source "simulator" and meta.simulated = true, so the backend labels everything SIMULATED and runs the
 * patient on its simulated clock (the replay can run faster than real time).
 */
class MockReplaySource(
    replayJson: String,
    private val patientId: String,
    private val minutesPerSecond: Double,
) : SensorSource {
    constructor(context: Context, patientId: String, minutesPerSecond: Double, asset: String = DEFAULT_ASSET) :
        this(context.assets.open(asset).bufferedReader().use { it.readText() }, patientId, minutesPerSecond)

    private val data = JSONObject(replayJson)
    private val stepMin = data.getInt("step_minutes").toLong()
    private val steps = data.getJSONArray("steps").let { a -> (0 until a.length()).map { a.getJSONObject(it) } }
    private val basis = data.getString("basis")
    private val rng = Random(1)

    private val _description = MutableStateFlow("Mock replay: ${data.getString("title")}")
    override val description = _description.asStateFlow()

    private var job: Job? = null
    private var emit: ((List<Reading>) -> Unit)? = null
    @Volatile private var simNow: Instant = Instant.now()
    @Volatile private var afUntil: Instant? = null
    @Volatile private var stillUntil: Instant? = null

    override fun start(scope: CoroutineScope, emit: (List<Reading>) -> Unit) {
        this.emit = emit
        val now = Instant.now().truncatedTo(ChronoUnit.MINUTES).let { it.minus(it.epochSecond / 60 % stepMin, ChronoUnit.MINUTES) }
        val live = steps.filter { it.getInt("o") >= 0 }
        // backfill: the replay hours before the live start, so the risk engine has history from the first update
        emit(steps.filter { it.getInt("o") < 0 }.flatMap { readingsFor(it, now.plus(it.getLong("o"), ChronoUnit.MINUTES)) })
        job = scope.launch {
            var loopStart = now
            val loopLen = (live.last().getLong("o") + stepMin)
            while (isActive) {
                for (s in live) {
                    simNow = loopStart.plus(s.getLong("o"), ChronoUnit.MINUTES)
                    emit(readingsFor(s, simNow))
                    delay((stepMin * 1000.0 / minutesPerSecond).toLong().coerceAtLeast(200))
                }
                loopStart = loopStart.plus(loopLen, ChronoUnit.MINUTES)
                _description.value = "Mock replay (looped): ${data.getString("title")}"
            }
        }
    }

    override fun stop() {
        job?.cancel()
        job = null
    }

    /** Same episode the backend's virtual watch makes: rapid AF for 60 simulated minutes. */
    override fun simulateAf() {
        afUntil = simNow.plus(60, ChronoUnit.MINUTES)
    }

    override fun simulateFall() {
        stillUntil = simNow.plus(30, ChronoUnit.MINUTES)
        emit?.invoke(listOf(reading(simNow, "fall", 1.0, null, mapOf("impact_g" to 3.4, "episode" to "simulated fall"))))
    }

    private fun readingsFor(s: JSONObject, t: Instant): List<Reading> {
        val out = mutableListOf<Reading>()
        val af = afUntil?.let { t.isBefore(it) } == true
        val minute = t.atZone(java.time.ZoneOffset.UTC).minute
        if (af) {
            val base = s.optDoubleOrNull("hr") ?: 90.0
            val hr = max(base + rng.nextDouble(35.0, 55.0), 132 + rng.nextDouble(0.0, 20.0)).coerceAtMost(250.0)
            out += reading(t, "hr", round1(hr), 0.95, mapOf("episode" to "simulated AF"))
            out += reading(t, "hrv_rmssd", round1(rng.nextDouble(90.0, 180.0)), 0.95, mapOf("basis" to "synthetic"))
            if (minute % 15 == 0) out += reading(t, "rhythm", "af_flutter", null, mapOf("episode" to "simulated AF"))
        } else {
            s.optDoubleOrNull("hr")?.let { out += reading(t, "hr", it, 0.95) }
            s.optDoubleOrNull("hrv")?.let { out += reading(t, "hrv_rmssd", it, 0.95, mapOf("basis" to "synthetic")) }
            s.optString("rhythm", "").takeIf { it.isNotEmpty() }?.let { out += reading(t, "rhythm", it, null) }
        }
        s.optDoubleOrNull("spo2")?.let { out += reading(t, "spo2", it, 0.95) }
        s.optDoubleOrNull("resp")?.let { out += reading(t, "resp", it, 0.95) }
        val still = stillUntil?.let { t.isBefore(it) } == true
        s.optDoubleOrNull("steps")?.let { out += reading(t, "steps", if (still) 0.0 else it, null, mapOf("basis" to "synthetic")) }
        s.optString("sleep", "").takeIf { it.isNotEmpty() }?.let { out += reading(t, "sleep_stage", it, null, mapOf("basis" to "synthetic")) }
        s.optDoubleOrNull("qtc")?.let { out += reading(t, "ecg_qtc", if (af) it + 15 else it, null, mapOf("basis" to "synthetic")) }
        return out
    }

    private fun reading(t: Instant, type: String, value: Any, quality: Double?, extra: Map<String, Any?> = emptyMap()) =
        Reading(patientId, t, type, value, Reading.SOURCE_SIMULATOR, quality,
            mapOf("simulated" to true, "label" to Reading.SIMULATED_LABEL, "basis" to basis) + extra)

    private fun round1(v: Double) = Math.round(v * 10) / 10.0

    companion object {
        const val DEFAULT_ASSET = "mock/replay_stay_37093652.json"
    }
}

private fun JSONObject.optDoubleOrNull(key: String): Double? = if (has(key) && !isNull(key)) optDouble(key) else null
